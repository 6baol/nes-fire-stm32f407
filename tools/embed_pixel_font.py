"""Rasterize the bundled OFL Press Start 2P font into an 8x8 Flash table."""
from pathlib import Path
import hashlib,json
from PIL import Image,ImageDraw,ImageFont
root=Path(__file__).resolve().parents[1]
source=root/'Assets/fonts/PressStart2P-Regular.ttf'
font=ImageFont.truetype(str(source),8)
rows=[]
for code in range(32,127):
    image=Image.new('L',(8,8));ImageDraw.Draw(image).text((0,0),chr(code),font=font,fill=255)
    rows.append([sum((1<<(7-x)) for x in range(8) if image.getpixel((x,y))>=128) for y in range(8)])
out=['/* Press Start 2P by CodeMan38; SIL OFL 1.1, see Assets/fonts/OFL.txt. */',
     '/* Generated by tools/embed_pixel_font.py; one byte per glyph row. */',
     'static const uint8_t pixel_glyphs[95][8]={']
out.extend('{'+','.join(hex(v) for v in glyph)+'}, /* '+str(i+32)+' */' for i,glyph in enumerate(rows))
out.append('};')
(root/'User/lcd/pixel_font_data.h').write_text('\n'.join(out)+'\n',encoding='ascii')
(root/'Assets/fonts/manifest.json').write_text(json.dumps({'family':'Press Start 2P','license':'OFL-1.1',
    'source':'https://github.com/google/fonts/tree/main/ofl/pressstart2p',
    'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'glyphs':95,'width':8,'height':8,'flash_bytes':760},indent=2),encoding='utf-8')
print('Packed 95 8x8 glyphs: 760 bytes; integer scaling, no antialiasing/framebuffer')

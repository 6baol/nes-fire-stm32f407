"""Pack custom PNG/JPG covers as indexed RGB565 palettes in firmware Flash.

Edit Assets/posters/posters.json: layout='poster' fills the 240x360 cover;
layout='screenshot' preserves the native capture before one LCD scaling pass.
Then run this script and build.ps1. Source images remain unchanged.
"""
from pathlib import Path
import json,hashlib
from PIL import Image,ImageOps

root=Path(__file__).resolve().parents[1]
assets=root/'Assets/posters'
config=json.loads((assets/'posters.json').read_text(encoding='utf-8'))['covers']

def literal(text):
    if any(ord(c)<32 or ord(c)>126 for c in text):
        raise ValueError('Current board font requires printable ASCII: '+text)
    return json.dumps(text)

def color(text):
    r,g,b=bytes.fromhex(text.lstrip('#'))
    return ((r>>3)<<11)|((g>>2)<<5)|(b>>3)

header='''/* Generated by tools/embed_posters.py. */
#ifndef NES_POSTERS_H
#define NES_POSTERS_H
#include <stdint.h>
typedef struct {
    const char *file;
    const uint8_t *pixels;
    const uint16_t *palette;
    uint16_t width,height,background,ink;
    const char *title[3];
    const char *edition,*system,*credit;
    const char *description[3];
    const char *cover_title,*cover_subtitle;
    uint8_t full_art,pixel_bits;
} NesPoster;
const NesPoster *NesPoster_Find(const char *file);
#endif
'''
lines=['/* Generated by tools/embed_posters.py; pixels indexed into RGB565. */',
       '#include "nes_posters.h"','#include <string.h>','#ifndef NES_SD_LIBRARY']
rows=[];reports=[];total=0
for i,entry in enumerate(config):
    full=entry.get('layout','poster')=='poster'
    path=assets/entry['image']
    original=Image.open(path).convert('RGB')
    size=(240,360) if full else original.size
    if not full and (size[0]>512 or size[1]>480):
        raise ValueError('Screenshot must be a native capture <=512x480; use poster for photographs')
    # Nearest-neighbour keeps existing NES title artwork crisp. Full posters
    # use a high quality fit so a replacement photograph/illustration is smooth.
    fitted=ImageOps.fit(original,size,method=Image.Resampling.LANCZOS) if full else original
    indexed=fitted.quantize(colors=256,method=Image.Quantize.MEDIANCUT)
    palette=indexed.getpalette();palette += [0]*(768-len(palette))
    values=[((palette[j]>>3)<<11)|((palette[j+1]>>2)<<5)|(palette[j+2]>>3) for j in range(0,768,3)]
    pixels=indexed.tobytes()
    bits=4 if max(pixels)<16 else 8
    palette_count=16 if bits==4 else 256
    if bits==4:
        pixels=bytes((pixels[j]<<4)|(pixels[j+1] if j+1<len(pixels) else 0) for j in range(0,len(pixels),2))
    flash_bytes=len(pixels)+palette_count*2;total+=flash_bytes
    lines.append(f'static const uint16_t palette_{i}[{palette_count}]={{'+','.join(hex(v) for v in values[:palette_count])+'};')
    lines.append(f'static const uint8_t pixels_{i}[{len(pixels)}]={{')
    lines.extend(','.join(str(b) for b in pixels[j:j+40])+',' for j in range(0,len(pixels),40))
    lines.append('};')
    title=(entry.get('title',[])+['']*3)[:3]
    desc=(entry.get('description',[])+['']*3)[:3]
    if any(len(t)>10 for t in title) or any(len(t)>21 for t in desc):
        raise ValueError('Cover title/description exceeds the side-panel width')
    if len(entry['cover_title'])>13 or len(entry['cover_subtitle'])>26 or len(entry['edition'])>21:
        raise ValueError('Cover caption/edition exceeds the available width')
    rows.append('{'+','.join([literal(entry['file']),f'pixels_{i}',f'palette_{i}',str(size[0]),str(size[1]),hex(color(entry['background'])),hex(color(entry['ink'])),
       '{'+','.join(map(literal,title))+'}',literal(entry['edition']),literal(entry['system']),literal(entry['credit']),
       '{'+','.join(map(literal,desc))+'}',literal(entry['cover_title']),literal(entry['cover_subtitle']),str(int(full)),str(bits)])+'}')
    reports.append({'file':entry['file'],'source':entry['image'],'source_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'width':size[0],'height':size[1],'pixel_bits':bits,'flash_bytes':flash_bytes})
if total>400*1024:raise ValueError('Poster Flash budget exceeded (400 KiB)')
lines+=['static const NesPoster posters[]={',',\n'.join(rows),'};',
'''const NesPoster *NesPoster_Find(const char *file)
{
    unsigned i;
    if(!file)return 0;
    for(i=0;i<sizeof(posters)/sizeof(posters[0]);i++)
        if(!strcmp(file,posters[i].file))return &posters[i];
    return 0;
}
''','#else','const NesPoster *NesPoster_Find(const char *file){(void)file;return 0;}','#endif']
(root/'User/nes/nes_posters.h').write_text(header,encoding='ascii')
(root/'User/nes/nes_posters.c').write_text('\n'.join(lines),encoding='ascii')
(assets/'manifest.json').write_text(json.dumps({'covers':reports,'total_flash_bytes':total},indent=2),encoding='utf-8')
print('Packed',len(rows),'covers;',total,'bytes of Flash; no framebuffer allocation')

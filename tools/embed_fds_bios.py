"""Embed a complete 8 KiB FDS BIOS into User/nes/nes_fds_bios.c so firmware can
bootstrap FDS disk images without a filesystem.

    python tools/embed_fds_bios.py

The BIOS is 8 KiB and lives at $E000-$FFFF on a real Famicom Disk System.
"""
from pathlib import Path
import argparse, hashlib, json

root = Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('bios',nargs='?',type=Path,help='complete 8 KiB BIOS; defaults to Roms/disksys.rom then fds_bios.bin')
args=parser.parse_args()
src=args.bios or (root/'Roms/disksys.rom' if (root/'Roms/disksys.rom').exists() else root/'Roms/fds_bios.bin')
dst = root / 'User/nes/nes_fds_bios.c'
header = root / 'User/nes/nes_fds_bios.h'

data = src.read_bytes()
if hashlib.sha1(data).hexdigest()=='1c5072bf66829491c3eb52cf26ba7731a7973944':
    raise SystemExit('Known corrupt BIOS: $F800 executable block contains game data. Supply a complete disksys.rom; embedded source was not changed.')
if len(data) != 8192:
    raise SystemExit(f'{src} is {len(data)} bytes, expected exactly 8192')

nmi = data[0x1FFA] | data[0x1FFB] << 8
reset = data[0x1FFC] | data[0x1FFD] << 8
irq = data[0x1FFE] | data[0x1FFF] << 8
if not (0xE000 <= reset <= 0xFFFF):
    raise SystemExit(f'reset vector ${reset:04X} is outside the BIOS window')

lines = ['/* Generated by tools/embed_fds_bios.py. Do not edit by hand. */',
         '#include "nes_fds_bios.h"',
         '',
         'const uint8_t nes_fds_bios[] = {']
for i in range(0, len(data), 24):
    lines.append(','.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',')
lines.append('};')
lines.append('const uint32_t nes_fds_bios_size = sizeof(nes_fds_bios);')
dst.write_text('\n'.join(lines) + '\n', encoding='ascii')

header.write_text('''#ifndef NES_FDS_BIOS_H
#define NES_FDS_BIOS_H
#include <stdint.h>
/* 8 KiB Famicom Disk System BIOS, mapped at $E000-$FFFF for mapper 20. */
extern const uint8_t nes_fds_bios[];
extern const uint32_t nes_fds_bios_size;
#endif
''', encoding='ascii')

(root/'Roms/bios.json').write_text(json.dumps({
    'source':str(src.relative_to(root)) if src.is_relative_to(root) else src.name,
    'bytes':len(data),'md5':hashlib.md5(data).hexdigest(),
    'sha1':hashlib.sha1(data).hexdigest(),'sha256':hashlib.sha256(data).hexdigest(),
    'vectors':{'nmi':nmi,'reset':reset,'irq':irq},
},indent=2),encoding='utf-8')

print(f'wrote {dst.relative_to(root)} ({len(data)} bytes)')
print(f'  NMI ${nmi:04X}  RESET ${reset:04X}  IRQ ${irq:04X}')
